#!/usr/bin/env node
// Regenerates NOTICES.md from package-lock.json and the in-tree licence
// files. The hand-written sections live in scripts/notices-preamble.md;
// everything below "## npm packages" is generated.
//
//   node scripts/gen-notices.mjs        # write NOTICES.md
//   node scripts/gen-notices.mjs --check  # fail if NOTICES.md is stale
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(path.join(ROOT, p), "utf8");

const lock = JSON.parse(read("package-lock.json"));
const prod = [];
for (const [key, value] of Object.entries(lock.packages)) {
  if (!key.startsWith("node_modules/") || value.dev || value.link) continue;
  prod.push({
    name: key.replace(/^node_modules\//, "").replace(/.*\/node_modules\//, ""),
    version: value.version ?? "",
    license: value.license
      ? Array.isArray(value.license)
        ? value.license.join(" OR ")
        : value.license
      : "(not declared)",
  });
}
prod.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const seen = new Set();
const rows = prod.filter((p) => {
  const k = `${p.name}@${p.version}`;
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
});

const byLicense = new Map();
for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

const texts = [
  ["MIT License", "packages/addons/physics/third_party/JoltPhysics/LICENSE"],
  ["Apache License 2.0", "packages/addons/geometry/third_party/manifold/LICENSE"],
  ["Mozilla Public License 2.0", "packages/addons/picg/third_party/CDT/LICENSE"],
  ["zlib License", "packages/addons/navigation/third_party/RecastNavigation/License.txt"],
  ["Boost Software License 1.0", "packages/addons/geometry/third_party/Clipper2/LICENSE"],
];

let out = read("scripts/notices-preamble.md").trimEnd() + "\n";

out += `\n## npm packages in the production tree\n\n`;
out += `${rows.length} packages resolve into the production dependency tree of this\n`;
out += `repository. Their licences, counted:\n\n| Licence | Packages |\n| --- | --- |\n`;
for (const [lic, n] of [...byLicense].sort((a, b) => b[1] - a[1])) out += `| ${lic} | ${n} |\n`;
out += `\nEach package's own licence text travels inside the package, under\n`;
out += `\`node_modules/<name>/\`, and is reproduced there by \`npm install\`.\n\n`;
out += `<details>\n<summary>Full list (${rows.length} packages)</summary>\n\n`;
out += `| Package | Version | Licence |\n| --- | --- | --- |\n`;
for (const r of rows) out += `| \`${r.name}\` | ${r.version} | ${r.license} |\n`;
out += `\n</details>\n`;

out += `\n## Licence texts\n\n`;
out += `The full text of each licence used by the vendored libraries above.\n`;
for (const [title, file] of texts) {
  out += `\n### ${title}\n\nReproduced from \`${file}\`.\n\n\`\`\`\n${read(file).trimEnd()}\n\`\`\`\n`;
}

out += `\n---\n\nGenerated by \`scripts/gen-notices.mjs\` from \`package-lock.json\` and the\n`;
out += `in-tree licence files. Re-run it after changing dependencies:\n\n`;
out += `\`\`\`\nnode scripts/gen-notices.mjs\n\`\`\`\n`;

if (process.argv.includes("--check")) {
  const current = read("NOTICES.md");
  if (current !== out) {
    console.error("NOTICES.md is out of date — run: node scripts/gen-notices.mjs");
    process.exit(1);
  }
  console.log(`NOTICES.md is up to date (${rows.length} npm packages).`);
} else {
  writeFileSync(path.join(ROOT, "NOTICES.md"), out);
  console.log(`Wrote NOTICES.md (${rows.length} npm packages, ${texts.length} licence texts).`);
}
