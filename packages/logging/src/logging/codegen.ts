/**
 * SAB Logging Layer — Code Generator (docs/SAB-LOGGING-LAYER-SPEC.md §2.3)
 *
 * Generates:
 * 1. generated/log-api.ts (Type-safe TypeScript logging methods)
 * 2. generated/log-formatters.ts (High-throughput worker formatting table)
 * 3. generated/log_codes.h (C++ header for native kernels and worker threads)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { LogCodeDefinition, LogArgSpec } from "./log-codes.js";

const logCodesModule = await import(
  fs.existsSync(new URL("./log-codes.js", import.meta.url))
    ? "./log-codes.js"
    : "./log-codes.ts"
);
const LOG_CODES: readonly LogCodeDefinition[] = logCodesModule.LOG_CODES;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// `npm run gen` runs this from dist/src/logging/codegen.js and the generated
// files must land in the tracked source tree (they are committed artifacts,
// same discipline as packages/schema/generated). From dist/src/logging the
// package root is 4 up; from src it is 2 up. Resolve by walking up to the
// directory that contains src/logging, prefer it, and let LOG_CODEGEN_OUT=dist
// target the compiled-relative tree instead (sandbox/reproducibility checks).
const upToPkgRoot = [4, 3, 2].find((up) => fs.existsSync(path.resolve(__dirname, Array(up).fill("..").join("/"), "src/logging/log-codes.ts")));
if (!upToPkgRoot) throw new Error("codegen: package root with src/logging not found (run via `npm run gen` from packages/logging)");
const OUT_DIR_SRC = path.resolve(__dirname, Array(upToPkgRoot).fill("..").join("/"), "src/logging/generated");
const OUT_DIR_DIST = path.resolve(__dirname, "./generated");
const OUT_DIR = process.env.LOG_CODEGEN_OUT === "dist" ? OUT_DIR_DIST : OUT_DIR_SRC;

if (!fs.existsSync(OUT_DIR)) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

function toCamelCase(str: string): string {
  return str
    .toLowerCase()
    .replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function toPascalCase(str: string): string {
  const c = toCamelCase(str);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

// =============================================================================
// 1. Generate TypeScript Producer API (`generated/log-api.ts`)
// =============================================================================
let tsApi = `/**
 * AUTO-GENERATED by packages/engine-core/src/logging/codegen.ts.
 * DO NOT EDIT DIRECTLY.
 */

import { LogLevel, LogProducer } from "../log-codes.js";
import type { LogProducerClient } from "../producer.js";

`;

for (const code of LOG_CODES) {
  const fnName = "log" + toPascalCase(code.name);
  const paramTypes = code.args
    .map((a: LogArgSpec) => `${a.name}: ${a.type}`)
    .join(", ");
  const paramsWithComma = code.args.length > 0 ? `, ${paramTypes}` : "";
  const callArgs = [
    code.level,
    `0x${code.id.toString(16).padStart(4, "0")}`,
    "entityRef",
    ...code.args.map((a: LogArgSpec) => a.name),
  ];

  tsApi += `/** ${code.format} */\n`;
  tsApi += `export function ${fnName}(logger: LogProducerClient${paramsWithComma}, entityRef?: bigint): boolean {\n`;
  tsApi += `  return logger.emit(${callArgs.join(", ")});\n`;
  tsApi += `}\n\n`;
}

fs.writeFileSync(path.resolve(OUT_DIR, "log-api.ts"), tsApi, "utf8");
console.log("Generated generated/log-api.ts");

// =============================================================================
// 2. Generate TypeScript Formatter Table (`generated/log-formatters.ts`)
// =============================================================================
let tsFormatters = `/**
 * AUTO-GENERATED by packages/engine-core/src/logging/codegen.ts.
 * DO NOT EDIT DIRECTLY.
 */

import type { LogRecordView } from "../log-record.js";

export type LogFormatter = (rec: LogRecordView) => string;

export const LOG_FORMATTERS: ReadonlyMap<number, LogFormatter> = new Map([\n`;

for (const code of LOG_CODES) {
  // Format string replacement: {0}, {1}, etc.
  let fmtExpr = JSON.stringify(code.format);
  for (let i = 0; i < code.args.length; i++) {
    fmtExpr = fmtExpr.replace(`{${i}}`, `" + (rec.args[${i}] ?? "") + "`);
  }
  tsFormatters += `  [0x${code.id.toString(16).padStart(4, "0")}, (rec: LogRecordView) => ${fmtExpr}],\n`;
}

tsFormatters += `]);\n`;

fs.writeFileSync(path.resolve(OUT_DIR, "log-formatters.ts"), tsFormatters, "utf8");
console.log("Generated generated/log-formatters.ts");

// =============================================================================
// 3. Generate C++ Header (`generated/log_codes.h`)
// =============================================================================
let cppHeader = `// AUTO-GENERATED by packages/engine-core/src/logging/codegen.ts.
// DO NOT EDIT DIRECTLY.

#pragma once

#include <cstdint>

namespace mmo::logging {

enum class LogLevel : uint8_t {
  Trace = 0,
  Debug = 1,
  Info  = 2,
  Warn  = 3,
  Error = 4
};

enum class LogProducer : uint8_t {
  Gateway = 0,
  Sim     = 1,
  Persist = 2,
  World   = 3,
  Native  = 4,
  Client  = 5,
  Admin   = 6
};

#pragma pack(push, 1)
struct LogRecord {
  uint8_t  level;
  uint8_t  producer;
  uint16_t code;
  uint32_t tick;
  uint64_t timestamp_ns;
  uint64_t entity_ref;
  uint64_t args[4];
  char     inline_string[64];
  uint32_t arg_tags;
  uint16_t flags;
  uint16_t version;
};
#pragma pack(pop)
static_assert(sizeof(LogRecord) == 128, "LogRecord must be exactly 128 bytes");

namespace codes {
`;

for (const code of LOG_CODES) {
  cppHeader += `constexpr uint16_t ${code.name} = 0x${code.id.toString(16).padStart(4, "0")}; // ${code.format}\n`;
}

cppHeader += `} // namespace codes

} // namespace mmo::logging
`;

fs.writeFileSync(path.resolve(OUT_DIR, "log_codes.h"), cppHeader, "utf8");
console.log("Generated generated/log_codes.h");
