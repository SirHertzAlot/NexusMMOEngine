// Regenerate generated/node_manifest_embedded.hpp from the vendored
// third_party/pcg-core/node-manifest.json (run after updating PICG):
//   node scripts/gen-manifest-header.mjs
//
// Upstream embeds the manifest (~1 MB) as ONE raw string literal, which
// MSVC rejects (C2026: a literal is capped near 16 KB). Here it becomes an
// array of pieces under that cap, split on character boundaries, which
// node_contracts.cpp joins before parsing (see VENDORING.md).

import { readFileSync, writeFileSync } from "node:fs";

const here = new URL("..", import.meta.url);
const json = readFileSync(new URL("third_party/pcg-core/node-manifest.json", here), "utf8");
const MAX_BYTES = 12000;
const pieces = [];
let piece = "";
let bytes = 0;
for (const ch of json) {
  const n = Buffer.byteLength(ch);
  if (bytes + n > MAX_BYTES) {
    pieces.push(piece);
    piece = "";
    bytes = 0;
  }
  piece += ch;
  bytes += n;
}
if (piece) pieces.push(piece);
if (pieces.some((p) => p.includes(")PCGMANIFEST\""))) throw new Error("manifest contains the raw-string delimiter");

const out = `#pragma once
// Generated by scripts/gen-manifest-header.mjs from
// third_party/pcg-core/node-manifest.json. Do not edit.

namespace pcg::internal::elements {

inline constexpr const char* kNodeManifestJsonParts[] = {
${pieces.map((p) => `R"PCGMANIFEST(${p})PCGMANIFEST"`).join(",\n")}
};

} // namespace pcg::internal::elements
`;
writeFileSync(new URL("generated/node_manifest_embedded.hpp", here), out);
console.log(`node_manifest_embedded.hpp: ${pieces.length} pieces, ${Buffer.byteLength(json)} bytes`);
